function Get-Insts {
    if ($script:insts) { return $script:insts }
    $script:insts = @(Get-CimInstance -Namespace root/wmi -ClassName EsifDeviceInformation -ErrorAction Stop)
    if ($script:insts.Count -eq 0) { throw '无 EsifDeviceInformation 实例' }
    return $script:insts
}
function Invoke-Esif([int]$iid, [int]$mid, [byte[]]$data) {
    if ($mid -gt 255) { throw "methodId=$mid >255：provider 只取低 8 字节(反汇编实锤)，此通道不支持，需走 ipf_uf" }
    # v1.3: CIM cmdlet 走 DMTF 宿主模式对该类报 WBEM_E_INVALID_PARAMETER(0x80041008)，
    # 改用 System.Management 在【类路径】上 ExecMethod（WMI 直接激活 provider，同 ipf_uf 内部方式）
    if (-not $script:esifClass) {
        Add-Type -AssemblyName System.Management
        $sc = New-Object System.Management.ManagementScope('root\wmi')
        $sc.Options.EnablePrivileges = $true
        $script:esifClass = New-Object System.Management.ManagementClass($sc, 'EsifDeviceInformation', $null)
        $script:esifClass.Get() | Out-Null
    }
    # 反汇编实锤(ipf_umdf2 0x180045800): inputData=NULL(空数组)→provider 直接报 0x8FC"无效的参数"
    if ($null -eq $data -or @($data).Count -eq 0) { $data = [byte[]](0x00) }
    try {
        $inParams = $script:esifClass.GetMethodParameters('EsifExecutePrimitive')
        $inParams.Properties['instanceId'].Value = [uint16]$iid
        $inParams.Properties['methodId'].Value = [uint16]$mid
        $inParams.Properties['inputData'].Value = [byte[]]$data
        $out = $script:esifClass.InvokeMethod('EsifExecutePrimitive', $inParams, $null)
    } catch {
        $h = ''
        if ($_.Exception -is [System.Management.ManagementException]) { $h = '(0x{0:X8})' -f [uint32]$_.Exception.ErrorCode }
        return [pscustomobject]@{ rc = 'EXC'; out = $null; err = ($h + ' ' + $_.Exception.Message) }
    }
    $od = $null
    if ($out.Properties['outputData']) { $od = $out['outputData'] }
    $hex = ''
    if ($od) { $hex = ((@($od) | ForEach-Object { ('{0:X2}' -f [int]$_) }) -join ' ') }
    $rcv = 0
    if ($out.Properties['returnCode']) { $rcv = [int]$out['returnCode'] }
    return [pscustomobject]@{ rc = $rcv; out = $hex; err = '' }
}
function Resolve-Prim([string]$s) {
    Load-Ids
    if ($s -match '^\d+$') {
        $mid = [int]$s
        $name = $script:idmap.PSObject.Properties | Where-Object { $_.Value -eq $mid } | Select-Object -First 1
        return @{ id = $mid; name = $(if ($name) { $name.Name } else { "PRIM_$mid" }) }
    }
    $cands = $script:idmap.PSObject.Properties | Where-Object { $_.Name -like ("GET_*" + $s.ToUpper() + "*") }
    if (-not $cands) { $cands = $script:idmap.PSObject.Properties | Where-Object { $_.Name -match $s -and $_.Name -like 'GET_*' } }
    if (-not $cands) { throw "找不到 GET 原语: $s（只读模式允许 GET_*）" }
    $c = @($cands) | Select-Object -First 1
    return @{ id = [int]$c.Value; name = $c.Name }
}
switch ($Action) {
    'list' {
        Load-Ids
        $want = 'GET_GPU_SPLIT_RATIO','GET_GPU_SPLIT_RATIO_ACTIVE','GET_GPU_SPLIT_RATIO_MAX','GET_NV_TGP_VALUE_AC','GET_PLATFORM_REST_OF_POWER','GET_PLATFORM_POWER_LIMIT','GET_PLATFORM_POWER_LIMIT_ENABLE','GET_POWER_SHARE_POLICY_POWER','GET_POWER_SHARE_EFFECTIVE_BIAS','GET_POWER_SHARE_TEMPERATURE_THRESHOLD','GET_GT_CLIP_REASONS','GET_IA_CLIP_REASONS','GET_INSTANTANEOUS_POWER','GET_EFFECTIVE_RAPL_POWER_LIMIT','GET_AC_PEAK_POWER','GET_ADAPTER_POWER_RATING','GET_ACTIVE_POWER_SCHEME','GET_AUTO_ENUM_LIST','GET_POWER_LIMIT_ENABLE','GET_PROC_THERMAL_DESIGN_POWER'
        foreach ($w in $want) { $v = $script:idmap.PSObject.Properties[$w]; if ($v) { '{0,4}  {1}' -f $v.Value, $w } }
        '（完整 751 项见 esif_primitive_ids.json）'
    }
    'probe' {
        if (-not $A1) { throw 'probe <GET原语名或ID> [最大instance 默认47]' }
        $p = Resolve-Prim $A1
        if ($p.name -notlike 'GET_*') { throw "拒绝非 GET 原语: $($p.name)" }
        if ($p.id -gt 255) { throw "原语 $($p.name) id=$($p.id) >255：此 WMI 通道 methodId 仅 8 位有效，需走 ipf_uf 管道" }
        $max = 47; if ($A2) { $max = [int]$A2 }
        $instN = (Get-Insts).Count
        "probe {0} (id={1}), instanceId 0..{2}  (类实例数={3})" -f $p.name, $p.id, $max, $instN
        $any = $false
        for ($i = 0; $i -le $max; $i++) {
            $r = Invoke-Esif $i $p.id $null
            $tag = if ($r.rc -eq 'EXC') { 'EXC' } elseif ($r.rc -eq 0) { 'OK' } else { "rc=$($r.rc)" }
            if ($r.rc -eq 0) { $any = $true }
            "  inst={0,-3} {1,-6} {2} {3}" -f $i, $tag, $r.out, $(if ($r.err) { $r.err.Substring(0, [Math]::Min(60, $r.err.Length)) } else { '' })
        }
        if (-not $any) { '  -> 全失败: inputData 可能需带 action 头, 用 get <inst> <id> <hex> 手工试' }
    }
    'get' {
        if (-not $A1 -or -not $A2) { throw 'get <instanceId> <原语名或ID> [inputData十六进制]' }
        $p = Resolve-Prim $A2
        if ($p.name -notlike 'GET_*') { throw "拒绝非 GET 原语: $($p.name)" }
        $data = $null
        if ($DataHex) { $data = [byte[]](($DataHex -split '\s+' | Where-Object { $_ }) | ForEach-Object { [convert]::ToInt32($_, 16) }) }
        $r = Invoke-Esif ([int]$A1) $p.id $data
        "inst={0} {1}(id={2}) rc={3} out=[{4}] {5}" -f $A1, $p.name, $p.id, $r.rc, $r.out, $r.err
    }
    'call' { throw 'v1 只读版禁用 call；写原语需单独方案确认后发新版' }
    default { '动作: list | probe <GET名/ID> [max] | get <inst> <名/ID> [hex]' }
}
